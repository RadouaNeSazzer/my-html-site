function setMetaContent(root, selector, value) {
  const element = root.querySelector(selector);
  if (element) element.setAttribute('content', value);
}

export function applyLocale(locale, root = typeof document === 'undefined' ? null : document) {
  const selectedLocale = locale === 'fr' ? 'fr' : 'ar';
  const content = translations[selectedLocale];
  if (!root) return content;

  root.documentElement.lang = content.lang;
  root.documentElement.dir = content.dir;
  root.title = content.title;
  setMetaContent(root, 'meta[name="description"]', content.description);
  setMetaContent(root, 'meta[property="og:title"]', content.title);
  setMetaContent(root, 'meta[property="og:description"]', content.description);
  setMetaContent(root, 'meta[property="og:locale"]', selectedLocale === 'ar' ? 'ar_DZ' : 'fr_DZ');

  for (const element of root.querySelectorAll('[data-i18n]')) {
    const key = element.dataset.i18n;
    const value = content.text[key];
    if (value) element.textContent = value;
  }

  const localeToggle = root.querySelector('[data-locale-toggle]');
  if (localeToggle) {
    localeToggle.textContent = content.localeToggle.text;
    localeToggle.setAttribute('aria-label', content.localeToggle.label);
  }

  try {
    globalThis.localStorage?.setItem('hotel-saharien-locale', selectedLocale);
  } catch {
    // Storage may be blocked by browser privacy settings; the page still works.
  }

  return content;
}
